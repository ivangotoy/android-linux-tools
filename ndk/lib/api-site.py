# Generate an autoconf CONFIG_SITE that marks every bionic function introduced after the target API as
# unavailable. Static links see the whole NDK libc.a, so configure's link-only AC_CHECK_FUNCS would
# otherwise "find" functions that the API-level headers do not declare (e.g. memset_explicit, API 34).
import os, re, sys
inc, api, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
names = {}
pat = re.compile(r'\b([A-Za-z_][A-Za-z0-9_]*)\s*\([^;{}]*?\)\s*(?:__[A-Za-z_]+(?:\([^;()]*\))?\s*)*__INTRODUCED_IN\((\d+)\)')
for dirpath, dirs, files in os.walk(inc):
    dirs.sort()
    for f in sorted(files):
        if not f.endswith('.h'):
            continue
        txt = open(os.path.join(dirpath, f), encoding='utf-8', errors='replace').read()
        txt = re.sub(r'/\*.*?\*/', ' ', txt, flags=re.S)
        txt = re.sub(r'^[ \t]*#.*?(?<!\\)$', ' ', txt, flags=re.M)
        for m in pat.finditer(txt):
            n, lvl = m.group(1), int(m.group(2))
            if lvl > api and not n.startswith('__'):
                names[n] = max(lvl, names.get(n, 0))
with open(out, 'w') as fh:
    fh.write('# generated by ndk/lib/api-site.py: bionic functions introduced after API %d\n' % api)
    for n in sorted(names):
        fh.write('ac_cv_func_%s=no  # API %d\n' % (n, names[n]))
        fh.write('ac_cv_have_decl_%s=no\n' % n)
print(len(names), 'functions after API', api)
