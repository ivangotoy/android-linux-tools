# Sourced by ndk/build.sh inside the builder container. Cross environment for aarch64-linux-android.
TARGET=aarch64-linux-android
API=35
BUILD_TRIPLE=x86_64-pc-linux-gnu
TC=/opt/ndk/toolchains/llvm/prebuilt/linux-x86_64
SYSROOT=$TC/sysroot
B=/work/build
# DEPROOT: private sysroot of the recipe being built (only its declared dependencies, set by build.sh)
# PKGDIR:  where a library recipe installs its headers/.a/.pc for dependants
DEPROOT=${DEPROOT:-$B/sysroot/none}
PKGDIR=${PKGDIR:-$B/pkg/none}
OUT=/work/out
DL=/work/dl
SRCROOT=/src
export TARGET API BUILD_TRIPLE TC SYSROOT

export CC="$TARGET$API-clang"
export CXX="$TARGET$API-clang++"
export CPP="$CC -E"
export AR=llvm-ar RANLIB=llvm-ranlib NM=llvm-nm STRIP=llvm-strip OBJCOPY=llvm-objcopy OBJDUMP=llvm-objdump
export READELF=llvm-readelf LD=ld.lld
export CC_FOR_BUILD=gcc BUILD_CC=gcc HOSTCC=gcc CPP_FOR_BUILD="gcc -E"

PREFIX_MAP="-ffile-prefix-map=$B/src=/usr/src -ffile-prefix-map=$DEPROOT=/usr -ffile-prefix-map=$SYSROOT=/ndk-sysroot"
export CFLAGS="-O2 -g0 -fPIC -fstack-protector-strong -D_FORTIFY_SOURCE=2 -ffunction-sections -fdata-sections $PREFIX_MAP"
export CXXFLAGS="$CFLAGS"
export CPPFLAGS="-I$DEPROOT/include"
LDFLAGS_BASE="-L$DEPROOT/lib -Wl,--gc-sections -Wl,--build-id=sha1"
export LDFLAGS="$LDFLAGS_BASE -static"
LT_LDFLAGS="$LDFLAGS -all-static"

# set_linkage: called after the recipe is sourced. LINKAGE=static (default): fully static against the NDK
# libc.a. LINKAGE=dynamic: PIE linked against the system bionic libc.so/libm.so/libdl.so (API $API stubs)
# only; every third-party library is still linked statically from $DEPROOT. Used for tools that resolve
# names, because static bionic has no netd client (libc/bionic/NetdClient.cpp is not built for libc.a),
# so getaddrinfo() in a static binary cannot reach the Android DNS resolver.
set_linkage() {
  case "${LINKAGE:=static}" in
    static) export LDFLAGS="$LDFLAGS_BASE -static"; LT_LDFLAGS="$LDFLAGS -all-static" ;;
    dynamic) export LDFLAGS="$LDFLAGS_BASE"; LT_LDFLAGS="$LDFLAGS" ;;
    *) echo "bad LINKAGE=$LINKAGE" >&2; return 1 ;;
  esac
}
export PKG_CONFIG="pkgconf --static"
export PKG_CONFIG_LIBDIR="$DEPROOT/lib/pkgconfig:$DEPROOT/share/pkgconfig"
unset PKG_CONFIG_PATH PKG_CONFIG_SYSROOT_DIR
export LC_ALL=C TZ=UTC
# configure cache: bionic functions introduced after $API are unavailable (generated by build.sh)
export CONFIG_SITE=$B/api-site.sh
export JOBS=${JOBS:-8}

CONFIGURE_HOST=(--host="$TARGET" --build="$BUILD_TRIPLE" --prefix=/usr --sysconfdir=/etc --localstatedir=/var
                --disable-shared --enable-static --disable-nls)

# configure_std [args...]: autoconf configure for target with static libs installed into $DEPROOT
configure_std() {
  ./configure "${CONFIGURE_HOST[@]}" "$@"
}

# install_lib [make args/targets, default: install]: make DESTDIR into a scratch dir, then merge usr/ into $PKGDIR (headers, .a, .pc)
install_lib() {
  local d="$B/destdir/$NAME"
  rm -rf "$d"
  [ $# -gt 0 ] || set -- install
  make DESTDIR="$d" "$@"
  if [ -d "$d/usr" ]; then
    mkdir -p "$PKGDIR"
    cp -a "$d/usr/." "$PKGDIR/"
  fi
  find "$PKGDIR" -name '*.la' -delete 2>/dev/null || true
}

# install_bin FILE [NAME]: strip and place a target executable into /work/out/bin
install_bin() {
  local f=$1 n=${2:-$(basename "$1")}
  mkdir -p "$OUT/bin"
  $STRIP --strip-all -o "$OUT/bin/$n" "$f"
  chmod 0755 "$OUT/bin/$n"
  echo "$n" >> "$B/meta/$NAME.bins"
}
